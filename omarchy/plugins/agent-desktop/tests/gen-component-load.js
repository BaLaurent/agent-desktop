#!/usr/bin/env node
// Generates tests/qml/tst_component_load.qml — the compile gate.
//
// The list is derived rather than hand-maintained because the exclusion rule is
// TRANSITIVE and easy to get wrong by hand: a component is unloadable by
// qmltestrunner if it imports Quickshell (whose QML plugin is statically linked
// into the quickshell binary) OR if it instantiates any component that is
// itself unloadable. `SettingsPage` compiles fine on its own but embeds
// `KnowledgeSettings`, which shells out through Quickshell.execDetached — so the
// engine cannot resolve it here and the gate would report a permanent, bogus
// failure.
//
//   node tests/gen-component-load.js            # write
//   node tests/gen-component-load.js --check    # exit 1 if it would change
const fs = require('fs')
const path = require('path')

const ROOT = path.join(__dirname, '..')
const OUT = path.join(__dirname, 'qml', 'tst_component_load.qml')
const CHECK = process.argv.includes('--check')

const DIRS = ['components', 'components/settings']

const files = []
for (const d of DIRS) {
  const abs = path.join(ROOT, d)
  if (!fs.existsSync(abs)) continue
  for (const f of fs.readdirSync(abs).sort()) {
    if (f.endsWith('.qml')) files.push(path.posix.join(d, f))
  }
}

const src = new Map()
for (const rel of files) src.set(rel, fs.readFileSync(path.join(ROOT, rel), 'utf8'))

const basename = (rel) => path.basename(rel, '.qml')
const byName = new Map()
for (const rel of files) byName.set(basename(rel), rel)

const importsQuickshell = (rel) => /^import Quickshell/m.test(src.get(rel))

// Which plugin components does this file instantiate? Textual and deliberately
// generous: a `Name {` at the start of a line, where Name is a known component.
// Over-detection only widens the exclusion, which is the safe direction.
function referenced(rel) {
  const out = new Set()
  const text = src.get(rel)
  for (const name of byName.keys()) {
    if (basename(rel) === name) continue
    const re = new RegExp('(^|[^\\w.])' + name + '\\s*\\{', 'm')
    if (re.test(text)) out.add(name)
  }
  return out
}

const refs = new Map()
for (const rel of files) refs.set(rel, referenced(rel))

// Transitive closure of "cannot be loaded here".
const blocked = new Set(files.filter(importsQuickshell))
let grew = true
while (grew) {
  grew = false
  for (const rel of files) {
    if (blocked.has(rel)) continue
    for (const name of refs.get(rel)) {
      const dep = byName.get(name)
      if (dep && blocked.has(dep)) { blocked.add(rel); grew = true; break }
    }
  }
}

const loadable = files.filter((f) => !blocked.has(f))
const excluded = files.filter((f) => blocked.has(f))

const rows = loadable.map((f) => `    "../../${f}"`).join(',\n')
const excludedComment = excluded.map((f) =>
  `//   ${f}${importsQuickshell(f) ? '  (imports Quickshell)' : '  (embeds an excluded component)'}`
).join('\n')

const content = `// GENERATED by tests/gen-component-load.js — do not edit.
// Regenerate with: node tests/gen-component-load.js

import QtQuick
import QtTest

// Every component the QML engine can compile here, compiled once.
//
// This is the gate that catches the class of bug qmllint reports only as a
// Warning and that no other test can see: a syntax error, an assignment to a
// property the type does not have, or a component that references itself
// ("X is instantiated recursively"). All three make the engine refuse the file,
// and because components nest, one bad file silently takes out everything above
// it — a single bad \`anchors\` on a PopupCard inside StatusLine took out ChatView
// and with it the whole chat surface, and it reached the live shell first.
//
// COMPILE, not instantiate. Qt.createComponent reports exactly the errors that
// belong to the file itself and yields errorString() — the engine's own
// diagnostic. Instantiating would additionally fail on every unset
// \`required property\`, which is a fact about the caller, not the component.
//
// Excluded, transitively, because Quickshell's QML plugin is statically linked
// into the quickshell binary and unavailable to qmltestrunner:
${excludedComment}
Item {
  id: harness
  width: 400
  height: 300

  readonly property var componentPaths: [
${rows}
  ]

  TestCase {
    name: "ComponentCompile"
    when: windowShown

    function test_compiles_data() {
      var rows = []
      for (var i = 0; i < harness.componentPaths.length; i++) {
        rows.push({ tag: harness.componentPaths[i], path: harness.componentPaths[i] })
      }
      return rows
    }

    function test_compiles(row) {
      var c = Qt.createComponent(row.path, Component.PreferSynchronous)
      verify(c.status !== Component.Loading, row.path + " still loading")
      verify(c.status !== Component.Error, row.path + " -> " + c.errorString())
      compare(c.status, Component.Ready, row.path + " -> " + c.errorString())
    }
  }
}
`

const existing = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null
if (CHECK) {
  if (existing !== content) {
    console.error('tst_component_load.qml is out of sync. Run: node tests/gen-component-load.js')
    process.exit(1)
  }
  console.log(`gen-component-load --check: ok (${loadable.length} compiled, ${excluded.length} excluded)`)
} else {
  fs.writeFileSync(OUT, content)
  console.log(`gen-component-load: ${loadable.length} components compiled, ${excluded.length} excluded`)
  for (const f of excluded) console.log('  excluded: ' + f)
}
